#!/usr/bin/env node
/**
 * @fileoverview Envora CLI
 *
 * Commands:
 *   envora init               Create a starter config.envora
 *   envora format [file]      Format .envora file(s)
 *   envora format --check     Check formatting without writing
 *   envora check [file]       Validate and check a config file
 *   envora migrate <file>     Convert .env to .envora
 *   envora version            Show version
 *   envora help               Show help
 */

import { readFile, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

// Load package.json for version info
const pkg = JSON.parse(
  await readFile(path.join(__dirname, '..', 'package.json'), 'utf8')
);

// ─── Terminal helpers ─────────────────────────────────────────────────────────

const GREEN  = '\x1b[32m';
const RED    = '\x1b[31m';
const YELLOW = '\x1b[33m';
const BOLD   = '\x1b[1m';
const RESET  = '\x1b[0m';
const DIM    = '\x1b[2m';

const ok   = msg => console.log(`  ${GREEN}✔${RESET} ${msg}`);
const fail = msg => console.log(`  ${RED}✖${RESET} ${msg}`);
const info = msg => console.log(`  ${DIM}${msg}${RESET}`);
const head = msg => console.log(`\n${BOLD}${msg}${RESET}\n`);
const warn = msg => console.log(`  ${YELLOW}!${RESET} ${msg}`);

function banner() {
  console.log(`\n${BOLD}  ENVORA${RESET}  ${DIM}v${pkg.version}${RESET}`);
  console.log(`  ${DIM}Modern configuration for Node.js${RESET}\n`);
}

// ─── Commands ─────────────────────────────────────────────────────────────────

async function cmdInit() {
  banner();

  const configFile = 'config.envora';
  const exampleEnv = '.env.example';

  // Check if already exists
  let configExists = false;
  try {
    await access(configFile);
    configExists = true;
  } catch { /* not found */ }

  if (configExists) {
    warn(`${configFile} already exists — skipping`);
  } else {
    const starter = `# Envora Configuration
# Generated by: envora init

APP {
    name: "My Application"
    environment: "development"
    debug: true
    version: "1.0.0"
}

SERVER {
    host: "localhost"
    port: 3000
    url: "http://\${SERVER.host}:\${SERVER.port}"
}

DATABASE {
    host: "localhost"
    port: 5432
    name: "myapp"
    credentials {
        username: "admin"
        password: secret(env("DATABASE_PASSWORD", "changeme"))
    }
}

# Example with required environment variable:
# API {
#     key: env("API_KEY")
#     url: env("API_URL", "https://api.example.com")
# }
`;
    await writeFile(configFile, starter, 'utf8');
    ok(`Created ${configFile}`);
  }

  // .env.example
  let envExists = false;
  try {
    await access(exampleEnv);
    envExists = true;
  } catch { /* not found */ }

  if (envExists) {
    warn(`${exampleEnv} already exists — skipping`);
  } else {
    const envExample = `# Copy this file to .env and fill in your values
DATABASE_PASSWORD=your_database_password
API_KEY=your_api_key
API_URL=https://api.example.com
`;
    await writeFile(exampleEnv, envExample, 'utf8');
    ok(`Created ${exampleEnv}`);
  }

  console.log('');
  info('Environment configuration initialized.');
  info(`Edit ${configFile} to configure your application.`);
  console.log('');
}

async function cmdFormat(args) {
  const { Formatter } = await import('../src/formatter/Formatter.js');
  const { glob } = await importGlob();

  const checkMode = args.includes('--check');
  const fileArgs = args.filter(a => !a.startsWith('--'));

  // Collect files to format
  let files = [];
  if (fileArgs.length > 0) {
    files = fileArgs;
  } else {
    // Default: find all .envora files in current directory
    try {
      const { readdirSync } = await import('node:fs');
      const cwd = process.cwd();
      const all = readdirSync(cwd);
      files = all
        .filter(f => f.endsWith('.envora'))
        .map(f => path.join(cwd, f));
    } catch { /* ignore */ }
  }

  if (files.length === 0) {
    warn('No .envora files found');
    process.exit(0);
  }

  if (checkMode) {
    head('Format Check');
  } else {
    head('Formatting');
  }

  const formatter = new Formatter();
  let allFormatted = true;

  for (const file of files) {
    let source;
    try {
      source = await readFile(file, 'utf8');
    } catch (err) {
      fail(`Cannot read ${file}: ${err.message}`);
      allFormatted = false;
      continue;
    }

    let formatted;
    try {
      formatted = formatter.format(source, file);
    } catch (err) {
      fail(`Parse error in ${path.basename(file)}: ${err.message}`);
      allFormatted = false;
      continue;
    }

    if (source === formatted) {
      ok(`${path.basename(file)} — already formatted`);
    } else if (checkMode) {
      fail(`${path.basename(file)} — not formatted`);
      allFormatted = false;
    } else {
      await writeFile(file, formatted, 'utf8');
      ok(`${path.basename(file)} — formatted`);
    }
  }

  console.log('');

  if (checkMode && !allFormatted) {
    info('Run "envora format" to fix formatting.');
    process.exit(1);
  }
}

async function cmdCheck(args) {
  const { EnvoraLoader } = await import('../src/loaders/EnvoraLoader.js');
  const fileArg = args[0] ?? 'config.envora';

  head('Config Check');

  let source;
  try {
    source = await readFile(fileArg, 'utf8');
  } catch (err) {
    fail(`Cannot read ${fileArg}`);
    process.exit(1);
  }

  try {
    const loader = new EnvoraLoader();
    loader.parse(source, { file: fileArg });
    ok(`${path.basename(fileArg)} — valid`);
  } catch (err) {
    fail(`${path.basename(fileArg)} — ${err.message}`);
    if (err.line) info(`Line ${err.line}, column ${err.column}`);
    process.exit(1);
  }

  console.log('');
}

async function cmdMigrate(args) {
  const { Migrator } = await import('../src/migrate/Migrator.js');

  const envFile = args[0];
  if (!envFile) {
    fail('Usage: envora migrate <.env file>');
    process.exit(1);
  }

  head('Migration');

  let result;
  try {
    const migrator = new Migrator();
    result = await migrator.migrate(envFile);
  } catch (err) {
    fail(`Migration failed: ${err.message}`);
    process.exit(1);
  }

  const outFile = path.basename(envFile).replace(/^\.env/, 'config') + '.envora';

  let outExists = false;
  try {
    await access(outFile);
    outExists = true;
  } catch { /* ok */ }

  if (outExists) {
    warn(`${outFile} already exists — writing to ${outFile}.new`);
    await writeFile(outFile + '.new', result, 'utf8');
    ok(`Created ${outFile}.new`);
  } else {
    await writeFile(outFile, result, 'utf8');
    ok(`Created ${outFile}`);
  }

  console.log('');
  info('Review the generated file and adjust as needed.');
  console.log('');
}

function cmdVersion() {
  console.log(`envora ${pkg.version}`);
}

function cmdHelp() {
  banner();
  console.log(`  ${BOLD}Usage:${RESET}  envora <command> [options]\n`);
  console.log(`  ${BOLD}Commands:${RESET}`);
  console.log(`    ${GREEN}init${RESET}                Create a starter config.envora`);
  console.log(`    ${GREEN}format${RESET} [file]        Format .envora file(s)`);
  console.log(`    ${GREEN}format --check${RESET}        Check formatting (exit 1 if not formatted)`);
  console.log(`    ${GREEN}check${RESET} [file]         Validate and check a config file`);
  console.log(`    ${GREEN}migrate${RESET} <file>       Convert .env to .envora`);
  console.log(`    ${GREEN}version${RESET}              Show version`);
  console.log(`    ${GREEN}help${RESET}                 Show this help\n`);
  console.log(`  ${BOLD}Examples:${RESET}`);
  console.log(`    ${DIM}envora init${RESET}`);
  console.log(`    ${DIM}envora format config.envora${RESET}`);
  console.log(`    ${DIM}envora format --check${RESET}`);
  console.log(`    ${DIM}envora migrate .env${RESET}`);
  console.log(`    ${DIM}envora check config.envora${RESET}`);
  console.log('');
}

// ─── Glob helper (optional, graceful degradation) ────────────────────────────

async function importGlob() {
  // We don't list glob as a dependency — use basic fs instead
  return { glob: null };
}

// ─── Main dispatch ────────────────────────────────────────────────────────────

const [,, command, ...rest] = process.argv;

try {
  switch (command) {
    case 'init':
      await cmdInit();
      break;
    case 'format':
      await cmdFormat(rest);
      break;
    case 'check':
      await cmdCheck(rest);
      break;
    case 'migrate':
      await cmdMigrate(rest);
      break;
    case 'version':
    case '-v':
    case '--version':
      cmdVersion();
      break;
    case 'help':
    case '-h':
    case '--help':
    case undefined:
      cmdHelp();
      break;
    default:
      fail(`Unknown command: "${command}"`);
      console.log('  Run "envora help" for usage.');
      process.exit(1);
  }
} catch (err) {
  // Top-level error handling — never expose secret values
  if (err && err.format) {
    console.error('\n' + err.format() + '\n');
  } else {
    console.error(`\n  Error: ${err?.message ?? String(err)}\n`);
  }
  process.exit(1);
}
